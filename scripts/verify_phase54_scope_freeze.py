#!/usr/bin/env python3

"""Offline verifier for the Phase 54 scope-freeze artifact."""

from __future__ import annotations

import argparse
import json
import pathlib

from artifact_paths import repo_path


ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_ARTIFACT = ROOT / "test_vectors" / "phase54" / "compatibility-slice-baseline.json"


def load_json(path: pathlib.Path) -> dict:
    if not path.exists():
        raise SystemExit(f"missing artifact: {path}")
    return json.loads(path.read_text())


def require_keys(data: dict, keys: set[str], label: str) -> None:
    missing = sorted(keys - set(data.keys()))
    if missing:
        raise SystemExit(f"[{label}] missing keys: {missing}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Offline verifier for the Phase 54 scope-freeze artifact."
    )
    parser.add_argument(
        "--artifact",
        default=str(DEFAULT_ARTIFACT),
        help="Path to the Phase 54 compatibility-slice baseline artifact.",
    )
    args = parser.parse_args()

    artifact_path = pathlib.Path(args.artifact)
    artifact = load_json(artifact_path)

    require_keys(
        artifact,
        {
            "captured_at",
            "scenario",
            "accepted_slice",
            "scope_decisions",
            "oracle_baseline",
            "evidence_references",
            "metadata_path",
            "success",
        },
        "phase54 scope freeze",
    )
    if artifact["scenario"] != "phase54 compatibility slice freeze and oracle baseline":
        raise SystemExit("[phase54 scope freeze] unexpected scenario")
    if artifact["success"] is not True:
        raise SystemExit("[phase54 scope freeze] success != true")

    accepted_slice = artifact["accepted_slice"]
    require_keys(
        accepted_slice,
        {
            "object_family",
            "mutation_family",
            "detail_keys",
            "featured_relations_value",
            "manytype_to_official_truth_surface",
            "official_to_manytype_truth_surface",
            "excluded_variants",
        },
        "phase54 accepted slice",
    )
    if accepted_slice["detail_keys"] != ["description", "featuredRelations"]:
        raise SystemExit("[phase54 accepted slice] unexpected detail keys")
    if accepted_slice["featured_relations_value"] != ["description", "sourceObject"]:
        raise SystemExit("[phase54 accepted slice] unexpected featuredRelations value")
    if accepted_slice["manytype_to_official_truth_surface"]["label"] != "self-hosted-official":
        raise SystemExit("[phase54 accepted slice] unexpected manytype_to_official truth surface")
    if accepted_slice["official_to_manytype_truth_surface"]["label"] != "manytype_server":
        raise SystemExit("[phase54 accepted slice] unexpected official_to_manytype truth surface")
    if "AccountDelete parity" not in accepted_slice["excluded_variants"]:
        raise SystemExit("[phase54 accepted slice] AccountDelete exclusion missing")

    scope_decisions = artifact["scope_decisions"]
    require_keys(
        scope_decisions,
        {"account_delete", "official_to_manytype_server_requirement"},
        "phase54 scope decisions",
    )
    account_delete = scope_decisions["account_delete"]
    require_keys(
        account_delete,
        {
            "decision",
            "reason",
            "official_capture_path",
            "local_capture_path",
            "source_phase50_path",
        },
        "phase54 account delete",
    )
    if account_delete["decision"] != "defer":
        raise SystemExit("[phase54 account delete] decision != defer")
    for field in ("official_capture_path", "local_capture_path", "source_phase50_path"):
        if not repo_path(account_delete[field]).exists():
            raise SystemExit(f"[phase54 account delete] missing referenced file: {account_delete[field]}")

    local_requirement = scope_decisions["official_to_manytype_server_requirement"]
    if local_requirement.get("post_edit_reread_required") is not True:
        raise SystemExit("[phase54 scope decisions] post_edit_reread_required != true")

    oracle_baseline = artifact["oracle_baseline"]
    require_keys(
        oracle_baseline,
        {"preflight", "network_config_path", "client_yml_ready", "exercised_binaries"},
        "phase54 oracle baseline",
    )
    if oracle_baseline["preflight"] != "passed":
        raise SystemExit("[phase54 oracle baseline] preflight != passed")
    if oracle_baseline["client_yml_ready"] is not True:
        raise SystemExit("[phase54 oracle baseline] client_yml_ready != true")
    # client.yml is generated by `make start` and gitignored, so only the
    # recorded path can be checked offline; the harness checks the file.
    if not oracle_baseline["network_config_path"]:
        raise SystemExit("[phase54 oracle baseline] network config path missing")

    evidence = artifact["evidence_references"]
    require_keys(
        evidence,
        {
            "phase46_bundle_path",
            "phase46_manytype_to_official_show_path",
            "phase46_manytype_to_official_restart_show_path",
            "phase46_official_to_manytype_read_path",
            "phase46_official_to_manytype_reopen_read_path",
        },
        "phase54 evidence references",
    )
    for value in evidence.values():
        if not repo_path(value).exists():
            raise SystemExit(f"[phase54 evidence references] missing referenced file: {value}")

    metadata_path = repo_path(artifact["metadata_path"])
    if not metadata_path.exists():
        raise SystemExit(f"[phase54 scope freeze] missing metadata: {metadata_path}")

    print("[phase54 scope freeze] ok")
    print("phase54 scope freeze: PASSED")


if __name__ == "__main__":
    main()
